// RaceQueries returns the curated feature matrix expressed over the generated
// race schema (heat, race, crew, lane, split, elapsed_ms, split_ms,
// stroke_rate, speed, ts, ts_tz, day, odd, rank_hint).
func RaceQueries() []string {
	return []string{
		"SELECT heat, sum(elapsed_ms) OVER (ORDER BY split) FROM races",
		"SELECT heat, sum(elapsed_ms) OVER (PARTITION BY heat ORDER BY split, lane, elapsed_ms ROWS BETWEEN 1 PRECEDING AND 1 FOLLOWING) FROM races",
		"SELECT heat, count(*) OVER (PARTITION BY heat ORDER BY split, lane, elapsed_ms ROWS BETWEEN UNBOUNDED PRECEDING AND CURRENT ROW) FROM races",
		"SELECT heat, avg(split_ms) OVER (PARTITION BY heat ORDER BY split, lane, elapsed_ms ROWS BETWEEN 2 PRECEDING AND 2 FOLLOWING) FROM races",
		"SELECT heat, min(elapsed_ms) OVER (PARTITION BY heat ORDER BY split, lane, elapsed_ms ROWS BETWEEN 2 PRECEDING AND 1 FOLLOWING) FROM races",
		"SELECT heat, max(elapsed_ms) OVER (PARTITION BY heat ORDER BY split, lane, elapsed_ms ROWS BETWEEN 2 PRECEDING AND 1 FOLLOWING) FROM races",
		"SELECT heat, sum(rank_hint) OVER (ORDER BY split GROUPS BETWEEN 1 PRECEDING AND 1 FOLLOWING) FROM races",
		"SELECT heat, sum(elapsed_ms) OVER (ORDER BY split RANGE BETWEEN 1 PRECEDING AND 1 FOLLOWING) FROM races",
		"SELECT heat, sum(split_ms) OVER (ORDER BY split DESC RANGE BETWEEN 1 PRECEDING AND 1 FOLLOWING) FROM races",
		"SELECT heat, sum(rank_hint) OVER (ORDER BY rank_hint NULLS FIRST RANGE BETWEEN 100 PRECEDING AND CURRENT ROW) FROM races",
		"SELECT heat, sum(rank_hint) OVER (ORDER BY rank_hint NULLS LAST RANGE BETWEEN CURRENT ROW AND 100 FOLLOWING) FROM races",
		"SELECT heat, rank() OVER (PARTITION BY heat ORDER BY elapsed_ms) FROM races",
		"SELECT heat, dense_rank() OVER (PARTITION BY heat ORDER BY elapsed_ms) FROM races",
		"SELECT heat, percent_rank() OVER (PARTITION BY heat ORDER BY elapsed_ms) FROM races",
		"SELECT heat, cume_dist() OVER (PARTITION BY heat ORDER BY elapsed_ms) FROM races",
		"SELECT heat, ntile(3) OVER (PARTITION BY heat ORDER BY elapsed_ms) FROM races",
		"SELECT heat, row_number() OVER (PARTITION BY heat ORDER BY split, lane, elapsed_ms) FROM races",
		"SELECT heat, lag(elapsed_ms, 1, 0) OVER (PARTITION BY heat ORDER BY split, lane, elapsed_ms) FROM races",
		"SELECT heat, lead(elapsed_ms, 2, -1) OVER (PARTITION BY heat ORDER BY split, lane, elapsed_ms) FROM races",
		"SELECT heat, first_value(elapsed_ms) OVER (PARTITION BY heat ORDER BY split, lane, elapsed_ms ROWS BETWEEN 1 PRECEDING AND 1 FOLLOWING) FROM races",
		"SELECT heat, last_value(elapsed_ms) OVER (PARTITION BY heat ORDER BY split, lane, elapsed_ms ROWS BETWEEN 1 PRECEDING AND 1 FOLLOWING) FROM races",
		"SELECT heat, nth_value(elapsed_ms, 2) OVER (PARTITION BY heat ORDER BY split, lane, elapsed_ms ROWS BETWEEN 1 PRECEDING AND 2 FOLLOWING) FROM races",
		"SELECT heat, sum(elapsed_ms) OVER (PARTITION BY heat ORDER BY split, lane, elapsed_ms ROWS BETWEEN 1 PRECEDING AND 1 FOLLOWING EXCLUDE CURRENT ROW) FROM races",
		"SELECT heat, sum(elapsed_ms) OVER (PARTITION BY heat ORDER BY split, lane, elapsed_ms ROWS BETWEEN 1 PRECEDING AND 1 FOLLOWING EXCLUDE GROUP) FROM races",
		"SELECT heat, sum(elapsed_ms) OVER (PARTITION BY heat ORDER BY split, lane, elapsed_ms ROWS BETWEEN 1 PRECEDING AND 1 FOLLOWING EXCLUDE TIES) FROM races",
		"SELECT heat, sum(stroke_rate) OVER (ORDER BY stroke_rate RANGE BETWEEN 5 PRECEDING AND 5 FOLLOWING) FROM races",
		"SELECT heat, sum(stroke_rate) OVER (ORDER BY stroke_rate DESC NULLS LAST RANGE BETWEEN 5 PRECEDING AND 5 FOLLOWING) FROM races",
		"SELECT heat, sum(speed) OVER (ORDER BY speed RANGE BETWEEN 1 PRECEDING AND 1 FOLLOWING) FROM races",
		"SELECT heat, count(*) OVER (ORDER BY ts RANGE BETWEEN INTERVAL '2 minutes' PRECEDING AND CURRENT ROW) FROM races",
		"SELECT heat, sum(elapsed_ms) OVER (ORDER BY ts DESC RANGE BETWEEN INTERVAL '1 minute' PRECEDING AND CURRENT ROW) FROM races",
		"SELECT heat, sum(split_ms) OVER (ORDER BY ts NULLS FIRST RANGE BETWEEN INTERVAL '1 minute' PRECEDING AND INTERVAL '1 minute' FOLLOWING) FROM races",
		"SELECT heat, sum(lane) OVER (ORDER BY crew, heat, split, lane ROWS BETWEEN 1 PRECEDING AND 1 FOLLOWING) FROM races",
		"SELECT heat, sum(lane) OVER (ORDER BY crew DESC, heat DESC, split DESC, lane DESC ROWS BETWEEN 2 PRECEDING AND 2 FOLLOWING) FROM races",
		"SELECT heat, sum(rank_hint) FILTER (WHERE rank_hint > 500) OVER (PARTITION BY heat ORDER BY split, lane, elapsed_ms) FROM races",
		"SELECT heat, count(elapsed_ms) FILTER (WHERE elapsed_ms > 50000) OVER (ORDER BY split, lane, elapsed_ms ROWS BETWEEN 3 PRECEDING AND 3 FOLLOWING) FROM races",
	}
}

